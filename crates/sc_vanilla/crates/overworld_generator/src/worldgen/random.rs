//! Seeded random sources for world generation.
//!
//! - [`RandomSourceProvider`] trait (fork/identical/next-*/set-seed API)
//! - [`Xoroshiro128`] (splitmix-seeded xoroshiro128 variant)
//! - [`MtRandom`] (Mersenne-Twister-backed source)
//! - Private [`commons`] module: the seed-conversion + sampling helpers the
//!   Mersenne-Twister source needs (seed expansion, twist/temper core,
//!   integer-provider defaults, bounded-range helpers).

// ---------------------------------------------------------------------------
// RandomSourceProvider (random-source interface)
// ---------------------------------------------------------------------------

/// Seeded random-source interface.
///
/// Note: the overloaded `nextInt()` / `nextInt(max)` / `nextInt(min, max)`
/// map to [`Self::next_int`] / [`Self::next_int_max`] /
/// [`Self::next_int_range`], since Rust has no overloading.
pub trait RandomSourceProvider {
    /// Create a new RandomSource using the random long generated by [`Self::next_long`].
    fn fork(&mut self) -> Self
    where
        Self: Sized;

    fn identical(&self) -> Self
    where
        Self: Sized;

    /// Generate random integer between `i32::MIN` and `i32::MAX`.
    fn next_int(&mut self) -> i32;

    /// Generate random integer between 0 and max.
    fn next_int_max(&mut self, max: i32) -> i32;

    /// Generate a random int in the range min-max, include min and max.
    /// (min == max panics on division by zero, matching the reference.)
    fn next_int_range(&mut self, min: i32, max: i32) -> i32;

    fn next_bounded_int(&mut self, max: i32) -> i32;

    /// Generate random long between `i64::MIN` and `i64::MAX`.
    fn next_long(&mut self) -> i64;

    /// Generate random boolean.
    fn next_boolean(&mut self) -> bool;

    /// Next float 0-1.
    fn next_float(&mut self) -> f32;

    /// Next double 0-1.
    fn next_double(&mut self) -> f64;

    /// Next double -1~1 for Gaussian distribution.
    fn next_gaussian(&mut self) -> f64;

    /// Sets a new seed.
    fn set_seed(&mut self, seed: i64);

    fn get_seed(&self) -> i64;
}

// ---------------------------------------------------------------------------
// Xoroshiro128
// ---------------------------------------------------------------------------

/// Xoroshiro128 generator (seedfinding-style xoroshiro128 variant, not the
/// standard xoroshiro128++ — this implementation is authoritative).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Xoroshiro128 {
    seed: i64,
    s0: i64,
    s1: i64,
}

impl Xoroshiro128 {
    /// Builds a generator from an explicit seed (only explicit seeds are
    /// offered; time-based seeding has no place in deterministic
    /// generation).
    pub fn new(seed: i64) -> Self {
        let mut r = Self {
            seed: 0,
            s0: 0,
            s1: 0,
        };
        r.set_seed(seed);
        r
    }

    /// 64-bit left rotation.
    #[inline]
    fn rotate_left(x: i64, k: i32) -> i64 {
        x.rotate_left(k as u32)
    }

    /// Expands one seed into two state words (splitmix64).
    fn split_mix64_seed(seed: i64) -> [i64; 2] {
        let mut out = [0i64; 2];
        let mut z = seed as u64;
        for i in 0..2 {
            z = z.wrapping_add(0x9E37_9B97_F4A7_C15);
            let mut r = z;
            r = (r ^ (r >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
            r = (r ^ (r >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
            r ^= r >> 31;
            out[i] = r as i64;
        }
        if out[0] == 0 && out[1] == 0 {
            out[0] = 0x9E37_9B97_F4A7_C15u64 as i64;
            out[1] = !out[0];
        }
        out
    }
}

impl RandomSourceProvider for Xoroshiro128 {
    /// Forks a child generator seeded by one `next_long()` draw.
    fn fork(&mut self) -> Self {
        Xoroshiro128::new(self.next_long())
    }

    /// Rebuilds an identical generator from the same seed (does not copy
    /// the current state).
    fn identical(&self) -> Self {
        Xoroshiro128::new(self.seed)
    }

    /// Draws a non-negative `i32` from the low 31 bits of `next_long()`.
    fn next_int(&mut self) -> i32 {
        self.next_long() as i32 & i32::MAX
    }

    /// Draws an integer in `[0, max)` (0 when max == 0).
    fn next_int_max(&mut self, max: i32) -> i32 {
        if max == 0 {
            return 0;
        }
        self.next_int() % max
    }

    /// Draws an integer in `[min, max)`.
    fn next_int_range(&mut self, min: i32, max: i32) -> i32 {
        min + self.next_int() % (max - min)
    }

    /// Draws an integer in `[0, max]`.
    fn next_bounded_int(&mut self, max: i32) -> i32 {
        self.next_int_max(max.wrapping_add(1))
    }

    /// Advances the xoroshiro state and returns the output word.
    fn next_long(&mut self) -> i64 {
        let i = self.s0;
        let j = self.s1;
        let k = Self::rotate_left(i.wrapping_add(j), 17).wrapping_add(i);
        let j = j ^ i;
        self.s0 = Self::rotate_left(i, 49) ^ j ^ (j << 21);
        self.s1 = Self::rotate_left(j, 28);
        k
    }

    /// Draws a random boolean from the low bit.
    fn next_boolean(&mut self) -> bool {
        (self.next_long() & 1) != 0
    }

    /// Draws a float in [0, 1) from the top 24 bits.
    fn next_float(&mut self) -> f32 {
        ((self.next_long() as u64 >> 40) as f64 * (1.0 / (1u64 << 24) as f64)) as f32
    }

    /// Draws a double in [0, 1) from the top 53 bits.
    fn next_double(&mut self) -> f64 {
        let bits = self.next_long() as u64 >> 11;
        bits as f64 * (1.0 / (1u64 << 53) as f64)
    }

    /// Draws a Gaussian sample (Box-Muller over two doubles).
    fn next_gaussian(&mut self) -> f64 {
        let u1 = self.next_double();
        let u2 = self.next_double();
        (-2.0 * u1.ln()).sqrt() * (2.0 * std::f64::consts::PI * u2).cos()
    }

    /// Re-seeds the generator (splitmix expansion of the new seed).
    fn set_seed(&mut self, seed: i64) {
        self.seed = seed;
        let st = Self::split_mix64_seed(seed);
        self.s0 = st[0];
        self.s1 = st[1];
    }

    /// Returns the construction seed.
    fn get_seed(&self) -> i64 {
        self.seed
    }
}

