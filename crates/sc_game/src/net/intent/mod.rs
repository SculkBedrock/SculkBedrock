//! Game-domain outbound intents (protocol-independent).
//!
//! Structure mirrors `sc_network::protocol`: one payload struct per intent
//! in a topic file (`player` / `block` / `effects` / `item` / `inventory` /
//! `crafting`), plus the [`NetworkIntent`] enum here. No `client` / `server`
//! split: intents are game semantics, not wire directions.
//!
//! To add a new intent:
//! 1. define the payload struct in the matching topic file with
//!    `#[derive(GameIntent)]` + `#[intent(reliability, entity)]`
//!    (see [`IntentPayload`]; data-dependent cases like [`player::MovePlayer`]
//!    implement the trait manually);
//! 2. add one tuple variant below;
//! 3. if the intent is coalescible state or a lifecycle barrier, add one arm
//!    in `net::outbox` (`coalesce_key` / `is_coalescing_barrier`).
//! `kind()`, `reliability()` and `entity_id()` are generated by
//! `#[derive(GameIntents)]`, so no per-variant match needs hand editing.

pub mod block;
pub mod crafting;
pub mod damage;
pub mod effects;
pub mod inventory;
pub mod item;
pub mod player;

use sc_game_macros::GameIntents;

pub use block::{CorrectBlockPrediction, UpdateBlock};
pub use crafting::{CraftResponse, OpenCraftingStation};
pub use damage::{HurtEntity, SyncHealth};
pub use effects::{
    BlockBreakProgress, BlockBreakProgressCue, ParticleCue, PlayParticle, PlaySound, SoundCue,
};
pub use inventory::{
    ClosePlayerInventory, OpenPlayerInventory, ResyncInventory, SyncFurnaceProgress,
    SyncFurnaceWindow, UpdateInventorySlot,
};
pub use item::{
    DespawnItemEntity, MoveItemEntity, SpawnItemEntity, TakeItemEntity, UpdateItemStackSize,
};
pub use player::{MoveEntityAbsolute, MovePlayer, PlayerMoveMode, RemoveEntity, SetEntityMotion};

/// Intent categories: overwriteable state vs lossless reliable facts.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum IntentReliability {
    /// Latest state regenerated next tick (moves, effects, progress).
    OverwritableState,
    /// Lifecycle/world/inventory facts: explicit failure handling on full.
    ReliableFact,
}

/// Payload contract for one intent struct.
///
/// The `GameIntent` derive implements this from `#[intent(...)]`
/// attributes; structs with data-dependent semantics implement it by hand.
///
/// Mirrors `sc_network::protocol::MinecraftPacket::to_packets`: callers
/// publish the payload directly (`publisher.publish(PlaySound { .. })`)
/// and the payload converts itself into the enum, so no call site writes
/// the `NetworkIntent::` wrapper by hand.
pub trait IntentPayload {
    /// Intent category (see [`IntentReliability`]).
    fn reliability(&self) -> IntentReliability;
    /// Target entity runtime id (None without a target).
    fn entity_id(&self) -> Option<u64>;
    /// Wrap into the outbound enum (generated: same-named variant).
    fn into_intent(self) -> NetworkIntent;
}

/// Game-domain outbound intent (routed by target entity runtime id).
#[derive(Clone, Debug, GameIntents)]
pub enum NetworkIntent {
    OpenCraftingStation(OpenCraftingStation),
    CraftResponse(CraftResponse),
    /// Player position/rotation sync (targets other player entities).
    MovePlayer(MovePlayer),
    /// Entity position/rotation sync (network side owns byte encoding).
    MoveEntityAbsolute(MoveEntityAbsolute),
    /// Set entity velocity.
    SetEntityMotion(SetEntityMotion),
    /// Remove an entity.
    RemoveEntity(RemoveEntity),
    /// Block change (carries the world for receiver selection).
    UpdateBlock(UpdateBlock),
    /// Semantic sound cue; protocol ids stay in `sc_network`.
    PlaySound(PlaySound),
    PlayParticle(PlayParticle),
    BlockBreakProgress(BlockBreakProgress),
    SpawnItemEntity(SpawnItemEntity),
    MoveItemEntity(MoveItemEntity),
    DespawnItemEntity(DespawnItemEntity),
    /// Sync a survivor's new stack count after item merge.
    UpdateItemStackSize(UpdateItemStackSize),
    TakeItemEntity(TakeItemEntity),
    /// Sync player main-inventory slots; clients see new items without
    /// opening the inventory; routed to the player entity by id.
    UpdateInventorySlot(UpdateInventorySlot),
    /// Authoritative player inventory resync (rolls back client prediction).
    ResyncInventory(ResyncInventory),
    /// Sync authoritative health after damage.
    SyncHealth(SyncHealth),
    /// Hurt / death animation cue.
    HurtEntity(HurtEntity),
    /// Single-block prediction rollback, sent only to the predicting player.
    CorrectBlockPrediction(CorrectBlockPrediction),
    OpenPlayerInventory(OpenPlayerInventory),
    ClosePlayerInventory(ClosePlayerInventory),
    /// Sync authoritative furnace window slots; routed to the viewer by id.
    SyncFurnaceWindow(SyncFurnaceWindow),
    /// Sync furnace progress values; routed to the viewer by id.
    SyncFurnaceProgress(SyncFurnaceProgress),
}

// The enum itself is a payload (identity conversion), so generic publishers
// accept both bare structs and already-wrapped intents.
impl IntentPayload for NetworkIntent {
    fn reliability(&self) -> IntentReliability {
        NetworkIntent::reliability(self)
    }

    fn entity_id(&self) -> Option<u64> {
        NetworkIntent::entity_id(self)
    }

    fn into_intent(self) -> NetworkIntent {
        self
    }
}
