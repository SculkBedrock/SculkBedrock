//! 游戏域出站 intent（协议无关）。
//!
//! Game-domain outbound intents (protocol-independent).
//!
//! 结构镜像 `sc_network::protocol`：每个 intent 一个 payload 结构体，按主题
//! 分文件存放（`player` / `block` / `effects` / `item` / `inventory` /
//! `crafting`），外加本文件的 [`NetworkIntent`] 枚举。不区分 `client` /
//! `server`：intent 是游戏语义，不是线路方向。
//! Structure mirrors `sc_network::protocol`: one payload struct per intent
//! in a topic file (`player` / `block` / `effects` / `item` / `inventory` /
//! `crafting`), plus the [`NetworkIntent`] enum here. No `client` / `server`
//! split: intents are game semantics, not wire directions.
//!
//! 新增一个 intent 的步骤：
//! To add a new intent:
//! 1. 在对应主题文件中定义 payload 结构体，标注 `#[derive(GameIntent)]` +
//!    `#[intent(reliability, entity)]`（参见 [`IntentPayload`]；数据相关的
//!    情况如 [`player::MovePlayer`] 需手动实现 trait）；
//!    define the payload struct in the matching topic file with
//!    `#[derive(GameIntent)]` + `#[intent(reliability, entity)]`
//!    (see [`IntentPayload`]; data-dependent cases like [`player::MovePlayer`]
//!    implement the trait manually);
//! 2. 在下面枚举中加一个元组变体；
//!    add one tuple variant below;
//! 3. 若该 intent 是可合并状态或生命周期屏障，在 `net::outbox` 中加一个分支
//!    （`coalesce_key` / `is_coalescing_barrier`）。
//!    if the intent is coalescible state or a lifecycle barrier, add one arm
//!    in `net::outbox` (`coalesce_key` / `is_coalescing_barrier`).
//! `kind()`、`reliability()` 和 `entity_id()` 由 `#[derive(GameIntents)]`
//! 生成，无需手写逐变体的 match。
//! `kind()`, `reliability()` and `entity_id()` are generated by
//! `#[derive(GameIntents)]`, so no per-variant match needs hand editing.

pub mod block;
pub mod crafting;
